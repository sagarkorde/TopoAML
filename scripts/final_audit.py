"""Evidence inventory, numerical prediction checks and honest completion report."""
import hashlib
import json
import subprocess
import os
import xml.etree.ElementTree as ET
from pathlib import Path
import pandas as pd
from sklearn.metrics import average_precision_score
from topoaml.data import ROOT


def main():
    counts={};claims=[];verified=0
    for directory,expected in [('tabular',75),('graph',40),('elliptic2',20)]:
        reports=list((ROOT/f'results/{directory}').glob('*.json'));counts[directory]={'complete':len(reports),'expected':expected}
        for path in reports:
            report=json.loads(path.read_text());pred=path.with_name(path.stem+'_predictions.csv')
            d=pd.read_csv(pred,float_precision='round_trip')
            score=average_precision_score(d.y,d.probability)
            if abs(score-report['test']['average_precision'])>1e-8:raise ValueError(f'Metric mismatch {path}')
            if d.probability.isna().any() or not d.probability.between(0,1).all():raise ValueError('Invalid predictions')
            verified+=1
            claims.append({'claim':path.stem+' test average precision','experiment':'E5' if directory=='elliptic2' else 'E2/E3',
                           'predictions':str(pred.relative_to(ROOT)),'metrics':str(path.relative_to(ROOT)),
                           'manuscript':'Results and model table','verified_ap':score})
    pd.DataFrame(claims).to_csv(ROOT/'results/claim_traceability.csv',index=False)
    commit=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip()
    payload={'git_commit_at_audit':commit,'model_runs':counts,'prediction_metric_checks_passed':verified,
             'primary_comparison':json.loads((ROOT/'results/primary_comparison.json').read_text()),
             'full_study_complete':False,'blockers':['Full-text and indexing audit of all 40 leads incomplete',
                 'Full-background Elliptic2 baselines not reproduced','Wider predictive robustness and matched-capacity fusion incomplete',
                 'Historical within-step and label-availability timestamps not released','Human author details/declarations/approval pending',
                 'Current Scopus source quartile not independently verified','Full GPU pipeline not rerun in a fresh isolated environment']}
    (ROOT/'results/final_audit.json').write_text(json.dumps(payload,indent=2))
    fresh=ROOT/'results/fresh_core_tests.xml'
    fresh_text='Fresh isolated core smoke test not yet completed.'
    if fresh.exists():
        suite=ET.parse(fresh).getroot().find('testsuite')
        fresh_text=f"Fresh isolated core environment: {suite.attrib['tests']} tests, {suite.attrib['failures']} failures, {suite.attrib['errors']} errors. GPU model/data pipeline reproduction remains separate."
    text=f'''# Reproducibility audit

Audit commit: `{commit}`. A later packaging commit may include this report; use the final repository HEAD recorded by Git for release identification.

{verified} saved prediction files reproduce their reported average precision within 1e-8. Model counts: {json.dumps(counts)}. Configurations, five seeds, validation thresholds, graph validation histories, checkpoint files and prediction IDs are saved. Binary models and processed caches remain local and are regenerated by the documented pipeline.

{fresh_text}

Input acquisition uses a pinned upstream commit and checked Git-LFS hashes. Dataset manifests record counts, missingness and temporal coverage. Split lists are immutable under rerun. Raw files are excluded from Git. The primary protocol implementation was committed before test result inspection; this is not a public registered report.

Regenerate tables/figures: `python scripts/analyze.py`, then `python scripts/extended_analysis.py`. Regenerate manuscript: `python scripts/build_manuscript.py`. Regenerate optional summary materials: `python scripts/submission_extras.py`. Windows PDF export uses the saved Word export helper; visual rendering uses Poppler. The complete model pipeline is in `scripts/run_all.ps1`.

The primary comparison is inconclusive. Secondary intervals are descriptive. Coarse observation and unknown label timestamps, incomplete broader robustness, full-background benchmark reproduction, full bibliography claim checks and final author/journal declarations limit study completion. No full independent reproduction or submission readiness is claimed.
'''
    (ROOT/'results/reproducibility_audit.md').write_text(text,encoding='utf-8')
    (ROOT/'results/mathematical_validation_report.md').write_text('''# Mathematical validation

The test log in `results/tests.xml` records actual pytest results. Tests cover empty/isolated/disconnected graphs, paths and trees, unfilled cycles, filled triangles, hollow/filled tetrahedra, known weighted persistence, DAGs with undirected cycles, boundary-squared-zero mod 2, filtration face compatibility, empty/essential descriptors, future-edge invariance, bounded neighborhoods, training-only transforms, graph-model forward/backward passes and paired evaluation identity.

GUDHI computes persistence over the default field in tests and F2 in the empirical extraction; all listed example Betti numbers are field-independent. Static graph Betti counts are independently compared with NetworkX cycle bases. Tests passing validate the implemented cases, not every possible large complex or the empirical novelty of TopoAML.
''',encoding='utf-8')
    hashes=[]
    for directory in ['src','scripts','configs','data/manifests','data/splits','results','literature','manuscript','docs','supplementary']:
        for current,folders,files in os.walk(ROOT/directory):
            folders[:]=[d for d in folders if d not in ['node_modules','__pycache__','rendered']]
            for name in files:
                path=Path(current)/name
                if path.suffix in ['.pt','.joblib','.png','.pdf','.docx','.xlsx'] or path.name.endswith('_browser.txt'):continue
                if path.name in ['artifact_checksums.csv']:continue
                hashes.append({'path':str(path.relative_to(ROOT)),'sha256':hashlib.file_digest(path.open('rb'),'sha256').hexdigest(),'bytes':path.stat().st_size})
    pd.DataFrame(hashes).to_csv(ROOT/'results/artifact_checksums.csv',index=False)
    print(json.dumps(payload,indent=2))

if __name__=='__main__':main()
