import fs from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { Workbook, SpreadsheetFile } from '@oai/artifact-tool';
const data=JSON.parse(await fs.readFile(new URL('../literature/novelty_matrix.json',import.meta.url),'utf8'));
const wb=Workbook.create();const sheet=wb.worksheets.add('Novelty');
sheet.getRange('A2').values=[['TopoAML novelty audit']];
sheet.getRange('A2').format.font={bold:true,size:18,color:'#19334D'};
sheet.getRange(`A4:F${data.length+3}`).values=data;
sheet.getRange('A4:F4').format.fill='#19334D';
sheet.getRange('A4:F4').format.font={bold:true,color:'#FFFFFF'};
sheet.getRange(`A4:F${data.length+3}`).format.wrapText=true;
sheet.getRange(`A4:F${data.length+3}`).format.rowHeight=48;
sheet.getRange(`A4:F${data.length+3}`).format.verticalAlignment='center';
sheet.getRange('A:A').format.columnWidth=26;
sheet.getRange('B:C').format.columnWidth=31;
sheet.getRange('D:E').format.columnWidth=34;
sheet.getRange('F:F').format.columnWidth=52;
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'Novelty!A4:F11',tableMaxRows:8,tableMaxCols:6,maxChars:1500})).ndjson);
const image=await wb.render({sheetName:'Novelty',range:'A2:F11',scale:1.5});
await fs.writeFile(new URL('../literature/novelty_preview.png',import.meta.url),new Uint8Array(await image.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(fileURLToPath(new URL('../literature/novelty_matrix.xlsx',import.meta.url)));
